// Unit tests for the Claude Code session parser.
import assert from 'node:assert/strict';
import path from 'node:path';
import { after, describe, test } from 'node:test';
import { classifyCommand, countRetries, loadSessions, parseSession, projectsDir, verdict } from '../src/sessions.js';
import { HOUR, MIN, cleanup, makeHome, writeSession } from './helpers.js';

after(cleanup);

const T0 = Date.parse('2026-10-11T02:00:00.000Z');
const at = (minutes) => new Date(T0 + minutes * MIN).toISOString();
const base = (minutes, extra = {}) => ({ sessionId: 's-1', cwd: '/work/repo', gitBranch: 'feat', timestamp: at(minutes), ...extra });
const prompt = (minutes, content, extra) => ({ type: 'user', ...base(minutes, extra), message: { role: 'user', content } });
const bash = (minutes, id, command) => ({
  type: 'assistant',
  ...base(minutes),
  message: { role: 'assistant', content: [{ type: 'tool_use', id, name: 'Bash', input: { command } }] },
});
const result = (minutes, id, { content = 'ok', isError = false, toolUseResult } = {}) => ({
  type: 'user',
  ...base(minutes),
  message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: id, is_error: isError, content }] },
  ...(toolUseResult === undefined ? {} : { toolUseResult }),
});
const jsonl = (...records) => records.map((r) => (typeof r === 'string' ? r : JSON.stringify(r))).join('\n') + '\n';
const parse = (...records) => parseSession(jsonl(...records), '/p/s-1.jsonl');

/** One Bash run per [command, exitCode] pair, results in the toolUseResult.exitCode shape. */
function runs(...pairs) {
  const records = [prompt(0, 'go')];
  pairs.forEach(([command, code], i) => {
    records.push(bash(i * 2 + 1, `t${i}`, command));
    records.push(result(i * 2 + 2, `t${i}`, { isError: code !== 0, content: code ? `Exit code ${code}\nfailed` : 'ok', toolUseResult: { exitCode: code } }));
  });
  return parse(...records);
}

describe('session metadata', () => {
  test('reads id, cwd, branches and the time span', () => {
    const s = parse(prompt(0, 'Do it', { gitBranch: 'main' }), bash(5, 't1', 'git checkout -b feat'), result(6, 't1'), prompt(30, 'more', { gitBranch: 'feat' }));
    assert.equal(s.id, 's-1');
    assert.equal(s.file, '/p/s-1.jsonl');
    assert.deepEqual(s.cwds, ['/work/repo']);
    assert.deepEqual(s.branches, ['main', 'feat']);
    assert.equal(s.start, T0);
    assert.equal(s.end, T0 + 30 * MIN);
  });

  test('branches are ordered by last appearance and ignore "" and HEAD', () => {
    const s = parse(prompt(0, 'a', { gitBranch: 'one' }), prompt(1, 'b', { gitBranch: 'two' }), prompt(2, 'c', { gitBranch: 'HEAD' }), prompt(3, 'd', { gitBranch: '' }), prompt(4, 'e', { gitBranch: 'one' }));
    assert.deepEqual(s.branches, ['two', 'one']);
  });

  test('falls back to the file name when records carry no sessionId', () => {
    const s = parseSession(jsonl({ type: 'user', timestamp: at(0), cwd: '/r', message: { content: 'hi' } }), '/p/abc-123.jsonl');
    assert.equal(s.id, 'abc-123');
  });

  test('counts unreadable lines instead of failing (schema drift, half-written last line)', () => {
    const s = parse(prompt(0, 'ok'), 'not json', '42', '{"type":"user","timestamp":"2026-10-11T0');
    assert.equal(s.unreadableLines, 3);
    assert.equal(s.records, 1);
    assert.equal(s.task, 'ok');
  });

  test('a file with no usable records reports zero records', () => {
    const s = parseSession('\n\n', '/p/empty.jsonl');
    assert.equal(s.records, 0);
    assert.equal(s.start, null);
  });
});

describe('task: the first real user prompt', () => {
  test('string content', () => {
    assert.equal(parse(prompt(0, '  Fix the flaky test  '), prompt(1, 'second')).task, 'Fix the flaky test');
  });

  test('text blocks', () => {
    assert.equal(parse(prompt(0, [{ type: 'text', text: 'Add search' }, { type: 'image', source: {} }])).task, 'Add search');
  });

  test('skips meta records, local command output, interrupts and tool results', () => {
    const s = parse(
      prompt(0, 'Caveat: The messages below were generated by the user while running local commands.', { isMeta: true }),
      prompt(1, '<local-command-stdout>ok</local-command-stdout>'),
      prompt(2, '[Request interrupted by user]'),
      result(3, 'x'),
      prompt(4, 'Real task'),
    );
    assert.equal(s.task, 'Real task');
  });

  test('a slash command becomes "command args"', () => {
    const s = parse(prompt(0, '<command-message>fix is running…</command-message>\n<command-name>/fix</command-name>\n<command-args>issue 12</command-args>'));
    assert.equal(s.task, '/fix issue 12');
  });

  test('sidechain (subagent) prompts are not the task', () => {
    assert.equal(parse(prompt(0, 'subagent brief', { isSidechain: true }), prompt(1, 'Main task')).task, 'Main task');
  });

  test('no prompt gives an empty task', () => {
    assert.equal(parse(bash(0, 't', 'ls'), result(1, 't')).task, '');
  });
});

describe('Bash runs and their results', () => {
  test('toolUseResult.exitCode', () => {
    const [run] = runs(['npm test', 3]).runs;
    assert.equal(run.command, 'npm test');
    assert.equal(run.exitCode, 3);
    assert.equal(run.ok, false);
    assert.equal(run.test, true);
    assert.equal(run.done, true);
  });

  test('"Exit code N" text when toolUseResult has no exitCode', () => {
    const s = parse(bash(0, 't', 'pytest'), result(1, 't', { isError: true, content: 'Exit code 2\nE   assert 1 == 2' }));
    assert.equal(s.runs[0].exitCode, 2);
    assert.equal(s.runs[0].ok, false);
  });

  test('text content in block form', () => {
    const s = parse(bash(0, 't', 'pytest'), result(1, 't', { isError: true, content: [{ type: 'text', text: 'Error: Exit code 4\nboom' }] }));
    assert.equal(s.runs[0].exitCode, 4);
  });

  test('is_error without an exit code is a failure', () => {
    const s = parse(bash(0, 't', 'npm test'), result(1, 't', { isError: true, content: 'Command timed out' }));
    assert.equal(s.runs[0].ok, false);
    assert.equal(s.runs[0].exitCode, null);
  });

  test('interrupted is a failure', () => {
    const s = parse(bash(0, 't', 'npm test'), result(1, 't', { toolUseResult: { stdout: '', interrupted: true } }));
    assert.equal(s.runs[0].ok, false);
  });

  test('a result with no error and no exit code is a success', () => {
    const s = parse(bash(0, 't', 'npm test'), result(1, 't', { content: 'all good' }));
    assert.equal(s.runs[0].ok, true);
  });

  test('a run with no result (session ended) is unknown', () => {
    const s = parse(bash(0, 't', 'npm test'));
    assert.equal(s.runs[0].ok, null);
    assert.equal(s.runs[0].done, false);
  });

  test('non-Bash tools are ignored', () => {
    const s = parse({ type: 'assistant', ...base(0), message: { content: [{ type: 'tool_use', id: 'r', name: 'Read', input: { file_path: 'x' } }] } });
    assert.deepEqual(s.runs, []);
  });

  test('exit code masked by a pipe: exit 0 with failures in the output is a failure', () => {
    const s = parse(bash(0, 't', 'npm test 2>&1 | tail -20'), result(1, 't', { content: 'Tests: 2 failed, 10 passed', toolUseResult: { stdout: 'Tests: 2 failed, 10 passed', exitCode: 0 } }));
    assert.equal(s.runs[0].masked, true);
    assert.equal(s.runs[0].ok, false);
  });

  test('exit code masked by a pipe: exit 0 without failures is unknown, never a pass', () => {
    const s = parse(bash(0, 't', 'npm test | tail -5'), result(1, 't', { content: 'Tests: 10 passed', toolUseResult: { exitCode: 0 } }));
    assert.equal(s.runs[0].ok, null);
  });

  test('masked: runner FAIL markers count, but a passing test named "failed …" does not', () => {
    const masked = (output) => parse(bash(0, 't', 'npx jest | tail'), result(1, 't', { content: output, toolUseResult: { exitCode: 0 } })).runs[0].ok;
    assert.equal(masked(' FAIL  src/login.test.js\nTests: 3 passed'), false);
    assert.equal(masked('--- FAIL: TestLogin (0.00s)'), false);
    assert.equal(masked('# fail 2'), false);
    assert.equal(masked('  ✓ failed login is rejected\nfailed logins are counted\nTests: 0 failed, 3 passed\n# fail 0'), null);
  });

  test('a masked run that exits non-zero is still a failure', () => {
    const s = parse(bash(0, 't', 'npm test | tail -5'), result(1, 't', { isError: true, content: 'Exit code 1\n' }));
    assert.equal(s.runs[0].ok, false);
  });

  test('set -o pipefail unmasks a pipe', () => {
    const s = parse(bash(0, 't', 'set -o pipefail; npm test | tail -5'), result(1, 't', { toolUseResult: { exitCode: 0 } }));
    assert.equal(s.runs[0].masked, false);
    assert.equal(s.runs[0].ok, true);
  });
});

describe('classifyCommand', () => {
  const cases = [
    ['npm test', true, false],
    ['npm run test:unit', true, false],
    ['pnpm lint', true, false],
    ['yarn typecheck', true, false],
    ['bun test', true, false],
    ['npx vitest run', true, false],
    ['./node_modules/.bin/jest --ci', true, false],
    ['node --test', true, false],
    ['python -m pytest -x', true, false],
    ['uv run pytest', true, false],
    ['bundle exec rspec', true, false],
    ['go test ./...', true, false],
    ['cargo test', true, false],
    ['make test', true, false],
    ['npx tsc --noEmit', true, false],
    ['ruff check .', true, false],
    ['CI=1 npm test', true, false],
    ['env CI=1 timeout 600 npm test', true, false],
    ['cd app && npm test', true, false],
    ['npm test && echo ok', true, false],
    ['npm test 2>&1 | tail -30', true, true],
    ['npm test; echo done', true, true],
    ['npm test || true', true, true],
    ['npm test;', true, false],
    ['npm run build', false, false],
    ['npm install', false, false],
    ['cat jest.config.js', false, false],
    ['git commit -m "fix tests"', false, false],
    ['ls test', false, false],
    ['', false, false],
    // Quotes and heredocs are data: "npm test" in a commit message is not a test run.
    ['git commit -m "$(cat <<\'EOF\'\nFix login\n\nnpm test\nEOF\n)"', false, false],
    ['cat <<EOF > notes.md\nnpm test\nEOF', false, false],
    ['cat <<EOF > notes.md && npm test\nbody\nEOF', true, false],
    ['echo "npm test; done"', false, false],
    ['grep -E "fail|error" log.txt', false, false],
    ["npm test -- -t 'a|b'", true, false],
    ['npm test \\\n  --coverage', true, false],
  ];
  for (const [command, isTest, masked] of cases) {
    test(JSON.stringify(command), () => {
      assert.deepEqual(classifyCommand(command), { test: isTest, masked });
    });
  }
});

describe('countRetries', () => {
  test('the same failing command 3 times is 2 retries', () => {
    assert.equal(countRetries(runs(['npm test', 1], ['npm test', 1], ['npm test', 1]).runs), 2);
  });

  test('fail, fail, pass is 2 retries', () => {
    assert.equal(countRetries(runs(['npm test', 1], ['npm test', 1], ['npm test', 0]).runs), 2);
  });

  test('re-running a passing command is not a retry', () => {
    assert.equal(countRetries(runs(['npm test', 0], ['npm test', 0], ['npm test', 0]).runs), 0);
  });

  test('different failing commands are not retries; whitespace is normalised', () => {
    assert.equal(countRetries(runs(['npm test', 1], ['npm run lint', 1], ['npm  test ', 1]).runs), 1);
  });

  test('parseSession fills retries', () => {
    assert.equal(runs(['pytest', 1], ['pytest', 1], ['pytest', 1]).retries, 2);
  });
});

describe('verdict: status from the last test/lint run', () => {
  test('last test run failed → FAILED, even if a later non-test command passed', () => {
    const s = runs(['npm test', 0], ['npm test', 1], ['git commit -m wip', 0]);
    const v = verdict(s.runs);
    assert.equal(v.status, 'FAILED');
    assert.equal(v.run.exitCode, 1);
  });

  test('passing after failing → PASSED', () => {
    assert.equal(verdict(runs(['npm test', 1], ['npm test', 0]).runs).status, 'PASSED');
  });

  test('no test commands → UNVERIFIED', () => {
    const v = verdict(runs(['ls', 0], ['npm run build', 1]).runs);
    assert.equal(v.status, 'UNVERIFIED');
    assert.equal(v.run, null);
  });

  test('no result for the last test → UNVERIFIED', () => {
    assert.equal(verdict(parse(bash(0, 't', 'npm test')).runs).status, 'UNVERIFIED');
  });

  test('no runs at all → UNVERIFIED', () => {
    assert.equal(verdict([]).status, 'UNVERIFIED');
  });
});

describe('loadSessions', () => {
  test('reads top-level *.jsonl in each project folder, skipping old files and other files', () => {
    const now = Date.now();
    const { projects } = makeHome();
    writeSession(projects, { id: 'new', cwd: '/r/one', start: now - HOUR, prompt: 'new' });
    writeSession(projects, { id: 'old', cwd: '/r/one', start: now - 40 * HOUR, prompt: 'old', mtime: now - 40 * HOUR });
    // Recent mtime but every record is outside the window (e.g. a copied file).
    writeSession(projects, { id: 'copied', cwd: '/r/two', start: now - 40 * HOUR, prompt: 'copied' });
    const loaded = loadSessions(projects, now - 24 * HOUR);
    assert.deepEqual(
      loaded.sessions.map((s) => s.id),
      ['new'],
    );
    assert.equal(loaded.unreadableLines, 0);
  });

  test('counts files with no usable records', async () => {
    const fs = await import('node:fs');
    const { projects } = makeHome();
    fs.mkdirSync(path.join(projects, '-r'), { recursive: true });
    fs.writeFileSync(path.join(projects, '-r', 'junk.jsonl'), 'garbage\n');
    fs.writeFileSync(path.join(projects, 'stray.jsonl'), '{}\n');
    const loaded = loadSessions(projects, Date.now() - HOUR);
    assert.equal(loaded.sessions.length, 0);
    assert.equal(loaded.emptyFiles, 1);
    assert.equal(loaded.unreadableLines, 1);
  });
});

